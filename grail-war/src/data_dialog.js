//  data_dialog.js … 続いていく会話（心の機微が大事な場面）
//
//  選択肢を一度選んで終わりではなく、言葉を交わしながら場面が進む「会話」の仕組みと、その場面たち。
//   ・英霊「月下の告白」   … 昔語り → 返す言葉 → 「あなたにとって、何なのか」 → 関係を告げる → 英霊の答え → 余韻
