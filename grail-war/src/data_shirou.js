// 会話の場面（初めて剣を交える前に一度だけ）
function fifthTalkScene(r, then) {
  r.fifthTalked = true;
  const seen = shirouMeet(r);
  const who = { shirou: '士郎', saber: 'アルトリア', enemy: FIFTH_SPEAKER[r.servantId] || '敵' };
  const lines = FIFTH_TALK[r.servantId].map(([sp, t]) => sp === 'narr' ? `<p>${t}</p>` : `<p class="talk ${sp}"><b>${who[sp]}</b>「${t}」</p>`);
  addLog(`第五次聖杯戦争の英霊「${servantOf(r).name}」と再会。`);
  scene({ title: '再会', sub: `${rivalLabel(r)}・${r.cls}`, reveal: true, body: [seen ? `<p>${seen}</p>` : '', ...lines].filter(Boolean),
    choices: [{ label: '剣を構える', cls: 'primary', icon: 'battle', fn: then }] });
}
