// 属性を動かす（数値は見せず、属性が切り替わった時だけ知らせる）
function alignShift(dl, dg) {
  const a = G.master.align; const before = alignLabel(a);
  a.law = clamp(a.law + dl, -ALIGN_MAX, ALIGN_MAX); a.good = clamp(a.good + dg, -ALIGN_MAX, ALIGN_MAX);
  const after = alignLabel(a);
  if (after !== before) {
    const [o1, m1] = before.split('・'); const [o2, m2] = after.split('・');
    const why = o1 !== o2 ? ALIGN_SHIFT_TEXT[o2] : ALIGN_SHIFT_TEXT[m2];
    note(`<span class="align-shift"><span class="tag gold">属性が変化した</span>${before} → <b>${after}</b><br><small>${why}</small></span>`);
    addLog(`属性が変化した：${before} → ${after}`);
  }
}
const ALIGN_SHIFT_TEXT = {
  秩序: '決まりや約束を重んじる心が、あなたの芯になりつつある。', 混沌: '何ものにも縛られない心が、あなたの中で育っている。', 中立: '決まりにも自由にも偏らない、自分なりの物差しを持ち始めた。',
  善: '誰かのために動ける心が、あなたの在り方になりつつある。', 悪: '自分のためなら手段を選ばない冷たさが、あなたの中に芽生えている。', 中庸: '善にも悪にも振れすぎない、静かな均衡があなたの中にある。',
};
// どちらにも寄らない選択：両方とも中立・中庸の側へ1戻る
function alignCenter() { const a = G.master.align; alignShift(-Math.sign(a.law), -Math.sign(a.good)); }

// 成長期の節目の最後に「心の天秤」を出す（通常のシナリオのみ。特殊シナリオは人物像が決まっているため出さない）
function alignCheck(then) {
  if (isFuji() || isKishi() || isShirou()) return then();
  const age = G.master.age;
  const pool = ALIGN_EVENTS.filter(e => e.age === age && !G.used[e.id]);
  if (!pool.length || ALIGN_EVENTS.some(e => e.age === age && G.used[e.id])) return then();
  const e = pick(pool);
  showEvent({
    id: e.id, title: e.title, chapter: `心の天秤　${age}歳`,
    text: `${e.text}<br><span class="note">――あなたの在り方が、静かに問われている。</span>`,
    choices: e.choices.map(c => ({ label: c.label, run: () => {
      if (c.mid) alignCenter(); else alignShift(c.law || 0, c.good || 0);
      addLog(`${age}歳「${e.title}」：${c.label.replace(/[「」]/g, '')}`);
      return [c.res];
    } })),
  }, then);
}
