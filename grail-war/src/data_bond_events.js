// 夜の語らいで、関係のイベントが起きやすい
function relationEvent() {
  if (!G.servant || !G.servant.special) return null;
  const t = isNight() ? 'night' : 'day';
  const list = BOND_EVENTS.filter(e => e.rel === G.servant.special && !G.used[e.id] && (e.time === 'any' || e.time === t) && (!e.cond || e.cond()));
  return list.length ? pick(list) : null;
}
