// 性格ごとの文章（無ければ knight の文章を使う）
// ob＝オベロン専用の文章（言葉が捻じ曲がる、特別な話し方のため。data_oberon.js 参照）
// 英霊ID（mash / meltryllis / artoria_caster など）をキーにした、その英霊専用の文章があればそれを使う
function svOwn(map) { const sv = servantOf(G); return map[sv.id] || (sv.id === 'oberon' && map.ob) || null; }
function PV(map) { const sv = servantOf(G); return fmt(svOwn(map) || map[sv.persona] || map.knight); }
// 話し方ごとの台詞（言葉を話さない英霊は地の文）
function RV(map) {
  const reg = voiceOf(servantOf(G)).reg;
  if (reg === 'mute') return fmt(map.mute);
  const ob = svOwn(map);
  return `<p class="quote">${applyTic(fmt(ob || map[reg] || map.polite))}</p>`;
}
// 能力値などをまとめて上げ、注記を返す
function rboost(o) {
  const parts = [];
  for (const [k, n] of Object.entries(o)) {
    if (k === 'bond') { bond(n); parts.push(`絆+${n}`); }
    else if (k === 'hp') { hp(n); parts.push(`HP+${n}`); }
    else if (k === 'shp') { shp(n); parts.push(`${SV()}のHP+${n}`); }
    else if (k === 'mp') { mp(n); parts.push(`${SV()}の魔力+${n}`); }
    else if (k === 'od') { od(n); parts.push(`オド+${n}`); }
    else { gain(k, n); parts.push(`${STAT_LABEL[k]}+${n}`); }
  }
  return `<span class="note">（${parts.join(' ')}）</span>`;
}
