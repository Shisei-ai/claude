// ---- どの人生になるか ----
function epiTrackOf(kind) {
  if (kind === 'dead' || kind === 'sealed' || !G.servant) return null;
  const rel = G.servant.special;
  if (isKishi() && kind !== 'together') return 'kishi_return';
  if (kind === 'together' && rel) return 'together_' + rel;
  if (['wish', 'wishKnown', 'devoured', 'saturated'].includes(kind)) return 'ruin';
  if (kind === 'abstain') return 'abstain';
  if (kind === 'lost') return 'lost';
  return 'parted';
}
function hasEpilogue(kind) { return !!epiTrackOf(kind); }

// =============================================================
//  進行
// =============================================================
function startEpilogue(kind) {
  const track = epiTrackOf(kind); if (!track) return titleScreen();
  const steps = EPI[track].slice();
  // 特殊シナリオの章を、年代順に差し込む
  const insert = st => { const i = steps.findIndex(x => x.y > st.y); steps.splice(i < 0 ? steps.length - 1 : i, 0, st); };
  if (isFuji()) insert(EPI_FUJI);
  if (isShirou()) { insert(EPI_SHIROU_A); insert(EPI_SHIROU_B); }
  if (isKishi() && kind === 'together') steps.unshift(EPI_KISHI);
  G.epi = { kind, track, steps, i: -1, year: 0, joy: 0, bond: 0, legacy: 0, marks: [] };
  G.phase = 'epilogue';
  chapterCard('エピローグ　その後の人生', () => epiNext());
}
function epiNext() {
  const e = G.epi; e.i++;
  if (e.i >= e.steps.length) return epiFinale();
  let st = e.steps[e.i];
  if (st.final && typeof avalonEligible === 'function' && avalonEligible()) st = e.steps[e.i] = EPI_MERLIN;   // 隠しエンディングへの分岐
  e.year = st.y;
  const go = () => scene({ title: st.title, sub: `エピローグ・${epiAgeLabel()}`, reveal: true,
    body: paras([fmt(st.text() + (st.kidNote ? st.kidNote() : ''))]),   // 子の有無で細部が変わる（data_family.js）
    choices: st.choices.filter(c => !c.cond || c.cond()).map(c => ({
      label: typeof c.label === 'function' ? c.label() : c.label, hint: c.hint,
      fn: () => { NOTES = []; const r = [].concat(c.run()).map(x => fmt(String(x))); next(st.title, paras(r), epiNext, st.final ? '生涯を閉じる' : '時が流れる'); },
    })) });
  if (!CFG.fx || e.i === 0) return go();
  showCard({ kicker: 'エピローグ', title: st.title, sub: /^kishi_/.test(e.track) ? epiAgeLabel() : `${e.year}年後・${epiAgeLabel()}`, cls: 'chapter', ms: 1400 }, go);
}
function epiFinale() {
  const e = G.epi;
  if (e.avalon) return avalonEnding();
  const best = ['joy', 'bond', 'legacy'].reduce((a, b) => e[b] > e[a] ? b : a, 'joy');
  const total = e.joy + e.bond + e.legacy;
  const kind = { joy: '幸福に満ちた生涯', bond: '絆に生きた生涯', legacy: '多くを遺した生涯' }[best];
  const n = Math.max(1, e.steps.length);   // 章が増えても評価が釣り合うよう、章数に比例させる
  const grade = total >= n * 3.05 ? '――満ち足りた、と言える一生だった。' : total >= n * 2.6 ? '――悔いはある。けれど、良い一生だった。' : '――決して平坦な道ではなかった。それでも、生き抜いた。';
  const title = `${EPI_TITLES[e.track] || 'その後の人生'}：${kind}`;
  markEpilogue(e.track); addLog(`エピローグ「${title}」`);
  sfx('win');
  showCard({ kicker: 'EPILOGUE', title: kind, cls: 'dawn', ms: 2000 }, () => {
    SCENE = { kind: 'ending', endKind: 'epilogue', epilogue: true, title: `エピローグ：${EPI_TITLES[e.track] || 'その後の人生'}`, good: true, text: [
      `<p>${M()}と${SV()}の物語は、こうして幕を下ろした。</p>`,
      `<div class="epi-scores"><div><span>幸福</span><b>${e.joy}</b></div><div><span>絆</span><b>${e.bond}</b></div><div><span>遺したもの</span><b>${e.legacy}</b></div></div>`,
      `<p><b>${kind}</b>${grade}</p>`,
      e.child ? `<p class="note">子：${e.child.name}――その血と想いは、次の世代へ受け継がれていく。</p>` : e.twoOnly ? '<p class="note">二人きりで歩み抜いた、穏やかな一生だった。</p>' : '',
      `<h3>生涯の記録</h3><ul class="clue-list">${e.marks.map(m => `<li>${m}</li>`).join('')}</ul>`,
    ] };
    TAB = 'story'; render();
  });
}
