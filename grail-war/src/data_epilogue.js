//  選択によって「幸福・絆・遺したもの」が積み重なり、最後に生涯の結末が決まる。
// =============================================================

const EPI_KEY = 'fukami-grail-war-epilogues';
const EPI_TITLES = {
  together_lover: '恋人として生きる', together_partner: '相棒として生きる', together_oath: '主従として生きる', together_family: '家族として生きる',
  parted: '別れの後で', ruin: '災厄の後で', lost: '敗者の春', abstain: '日常の向こう側', kishi_moon: '月の王と英霊', kishi_return: '月の王の観測',
};
function seenEpilogues() { try { return JSON.parse(localStorage.getItem(EPI_KEY) || '[]'); } catch (e) { return []; } }
function markEpilogue(k) { const s = seenEpilogues(); if (s.includes(k)) return; s.push(k); try { localStorage.setItem(EPI_KEY, JSON.stringify(s)); } catch (e) { } }

// 英霊の台詞を話し方ごとに（p丁寧 g王 r気さく o古風 c冷静 b明朗 m言葉なし）。王・古風は無ければ冷静の台詞を使う
function sq(m) {
  const reg = voiceOf(servantOf(G)).reg;
  if (reg === 'mute') return fmt(m.m || '（{s}が、静かに頷いた）');
  if (servantOf(G).id === 'oberon' && m.ob) return fmt(m.ob);   // オベロン専用の台詞
  const t = { polite: m.p, regal: m.g || m.c, rough: m.r, old: m.o || m.c, cool: m.c, bright: m.b || m.p }[reg] || m.c;
  return applyTic(fmt(t));
}
// 関係ごとに文章を変える（無ければ none）
function relText(map) { const k = (G.servant && G.servant.special) || 'none'; return fmt(map[k] || map.none); }
const SVN = () => G.servant ? servantOf(G).short : '英霊';
const friendLine = () => G.friend && G.rivals.some(r => r.friend) ? `${friendName()}も、` : '';
// 人生の節目の結果：点数を足して、記録に残す
function epiGain(o, mark) {
  const e = G.epi;
  for (const k of ['joy', 'bond', 'legacy']) e[k] += o[k] || 0;
  if (mark) e.marks.push(`${epiAgeLabel()}　${mark}`);
  return '';
}
function epiAge() { return (G.master.age || 18) + (G.epi ? G.epi.year : 0); }
function epiAgeLabel() { return G.epi && /^kishi_/.test(G.epi.track) ? (G.epi.year ? `${G.epi.year}年後` : 'あの冬') : `${epiAge()}歳`; }

