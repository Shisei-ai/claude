//  data_epilogue.js … エピローグ「その後の人生」
//
//  エンディングの後、「その後の人生へ」を選ぶと始まる。
//  本編と同じように、人生の節目ごとに選択肢を選んで進み、最期の日までを描く。
//
//  どの人生になるか（トラック）は、エンディング × 特別な関係 × シナリオで決まる
//   together_lover / partner / oath / family … 受肉した英霊と共に生きる（関係ごと）
//   parted   … 英霊と別れた後の人生（破壊・託す・願いなし・願いの成就 など。関係で文章が変わる）
//   ruin     … 聖杯の災厄の後の人生（歪んだ願い・承知の上の願い・黒い夜明け）
//   lost     … 脱落した後の人生
//   abstain  … 戦いから降りた後の人生
//   特殊シナリオ：藤丸は「旧友たち」の章が加わり、岸波は「月か、地上か」を選ぶ（月の王としての人生もある）
