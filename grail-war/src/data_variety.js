// まだ使っていない候補から選ぶ（全部使ったら、また最初から）
function pickFresh(key, list) {
  if (!list || !list.length) return '';
  const used = ((G.flags.fresh = G.flags.fresh || {})[key] = G.flags.fresh[key] || []);
  let idx = list.map((_, i) => i).filter(i => !used.includes(i));
  if (!idx.length) { used.length = 0; idx = list.map((_, i) => i); }
  const i = pick(idx); used.push(i); return list[i];
}

