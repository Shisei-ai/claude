const RE_SV_FILLER = ['冬の終わり', '新しい日々', '面影', '召喚陣の夢', '形見の手入れ', 'あの冬を知る者', '変わる街', '小さな聞き手'];
function routeEpiCompose(kind, track, steps) {
  const r = G.route3;
  if (!r || isFuji() || isShirou() || isKishi() || /^kishi_/.test(track)) return steps;
  const svCh = typeof EPI_SV_CH !== 'undefined' && G.servant ? EPI_SV_CH[G.servant.id] : null;
  if (r === 'servant') {
    let out = reTrimOther(reTrimOther(steps, 'friend'), 'miko');
    if (track === 'parted') out = out.concat([RE_SV.letter, RE_SV.moon]);
    return reSort(out);
  }
  if (r === 'miko') {
    let out = reTrimOther(steps, 'friend').filter(st => st !== svCh);   // 英霊ごとの思い出の章も、このルートでは外す
    if (!mikoHere() || !mkMet()) return reSort(out);
    const mine = new Set(Object.values(MIKO_EPI));
    out = out.filter(st => !mine.has(st));
    if (track === 'kami_keeper') {
      const fin = out.find(s => s.final);
      out = out.filter(s => !s.final).concat([RE_KEEP.bento, RE_KEEP.mistKagura, RE_MK.shirotae, RE_KEEP.foot, MIKO_EPI.old], fin ? [reKeeperFinal(fin)] : []);
      return reSort(out);
    }
    const body = reMikoMain();
    if (track === 'parted') out = out.filter(st => !RE_SV_FILLER.includes(st.title) && !st.final).concat([RE_MK.open], body, [RE_MK.final]);
    else out = out.concat(body);
    return reSort(out);
  }
  if (r === 'friend') {
    let out = reTrimOther(steps, 'miko').filter(st => st !== svCh);
    const main = reFriendMain(kind); if (!main) return reSort(out);
    const mine = new Set([...Object.values(FRIEND_EPI), ...Object.values(SK_EPI)]);
    out = out.filter(st => !mine.has(st));
    if (track === 'parted') out = out.filter(st => !RE_SV_FILLER.includes(st.title) && !st.final).concat(main);
    else out = out.concat(main.filter(s => !s.final && s.y > 0));
    return reSort(out);
  }
  return steps;
}
