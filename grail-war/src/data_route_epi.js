// ほかのヒロインの章は、最低限だけ（出会い直す春・恋人なら求婚。晩年は、結婚した相手のときだけ）
function reTrimOther(steps, who) {
  const pool = who === 'friend' ? FRIEND_EPI : MIKO_EPI;
  const keep = who === 'friend' ? ['spring', 'street', 'grave', 'propose'] : ['spring', 'propose', 'shrine', 'empty', 'mist'];
  const all = new Set(Object.values(pool)); const kept = new Set(keep.map(k => pool[k]));
  return steps.flatMap(st => {
    if (!all.has(st) || kept.has(st)) return [st];
    if (st === pool.old) return [{ ...st, skip: () => (st.skip && st.skip()) || !(who === 'friend' ? reFrSp() : reMkSp()) }];
    return [];
  });
}
// 年の順に並べ直す（最期の章は必ず最後。同じ年なら、元の順）
function reSort(steps) {
  const fin = steps.filter(s => s.final); const rest = steps.filter(s => !s.final);
  return rest.map((s, i) => [s, i]).sort((a, b) => a[0].y - b[0].y || a[1] - b[1]).map(x => x[0]).concat(fin.slice(-1));
}
