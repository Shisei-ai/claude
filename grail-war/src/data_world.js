// ---- ランク → 数値 ----
// 判定では「数値 + サイコロ」で勝負します。
function rankValue(r) {
  if (!r) return 0;
  if (r === '？') return 40;      // 不明：Bランク相当として扱う
  if (r === '－' || r === 'なし') return 30;
  const base = { E: 10, D: 20, C: 30, B: 40, A: 50, EX: 65 };
  const m = r.match(/^(EX|[A-E])(\+*)(-*)$/);
  if (!m) return 30;
  return base[m[1]] + m[2].length * 5 - m[3].length * 3;
}
// 数値 → 表示用ランク（マスター補正後の表示に使う）
function valueRank(v) {
  if (v >= 65) return 'EX';
  const table = [[60, 'A++'], [55, 'A+'], [50, 'A'], [45, 'B+'], [40, 'B'], [35, 'C+'], [30, 'C'], [25, 'D+'], [20, 'D'], [15, 'E+'], [0, 'E']];
  for (const [t, r] of table) if (v >= t) return r;
  return 'E';
}

