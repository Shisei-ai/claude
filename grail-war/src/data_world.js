// ---- クラス相性（FGOの三すくみをベースに簡略化） ----
// 戻り値: 攻撃側から見た補正値
function classAffinity(atk, def) {
  const adv = {
    'セイバー': ['ランサー', 'アルターエゴ'], 'ランサー': ['アーチャー', 'アルターエゴ'], 'アーチャー': ['セイバー', 'アルターエゴ'],
    'ライダー': ['キャスター', 'プリテンダー'], 'キャスター': ['アサシン', 'プリテンダー'], 'アサシン': ['ライダー', 'プリテンダー'],
    'ルーラー': ['ムーンキャンサー'], 'ムーンキャンサー': ['アヴェンジャー'], 'アヴェンジャー': ['ルーラー'],
    'アルターエゴ': ['ライダー', 'キャスター', 'アサシン', 'フォーリナー'], 'プリテンダー': ['セイバー', 'アーチャー', 'ランサー', 'アルターエゴ'],
    'フォーリナー': ['バーサーカー'],
  };
  if (atk === 'フォーリナー' && def === 'バーサーカー') return 8;
  if (atk === 'バーサーカー' && def === 'フォーリナー') return -4;
  if (atk === 'バーサーカー' || def === 'バーサーカー') return 6;   // 狂戦士は与える・受ける両方が大きい
  if ((adv[atk] || []).includes(def)) return 8;
  if ((adv[def] || []).includes(atk)) return -8;
  return 0;
}

