// ---- クラス相性（FGOの三すくみをベースに簡略化） ----
// 戻り値: 攻撃側から見た補正値
function classAffinity(atk, def) {
  const adv = {
    'セイバー': ['ランサー'], 'ランサー': ['アーチャー'], 'アーチャー': ['セイバー'],
    'ライダー': ['キャスター'], 'キャスター': ['アサシン'], 'アサシン': ['ライダー'],
    'アヴェンジャー': ['ルーラー'], 'ルーラー': [],
  };
  if (atk === 'バーサーカー' || def === 'バーサーカー') return 6;   // 狂戦士は与える・受ける両方が大きい
  if ((adv[atk] || []).includes(def)) return 8;
  if ((adv[def] || []).includes(atk)) return -8;
  return 0;
}

