// =============================================================
//  会話の台詞を、英霊ごとの言葉に差し替える
//   V(sv) が返す台詞集のうち low / mid / high / talk を、SV_TALK のものにする
//   （special / farewell / reunion は、もともと英霊ごとの固有台詞 SIG を使っている）
// =============================================================
{
  const baseV = V;
  V = function (sv) {
    sv = sv || servantOf(G);
    const base = baseV(sv); const own = SV_TALK[sv.id];
    return own ? { ...base, ...own } : base;
  };
  // 固有台詞だけを使う英霊（SIG_ONLY）も、英霊ごとの会話（SV_TALK）があれば、藤丸シナリオの思い出話を話せるように
  for (const id of Object.keys(SV_TALK)) SIG_ONLY.delete(id);
}
