// ---- 見透かす：マスターの今の様子を、ぶっきらぼうに言い当てる ----
function oberonSeeThrough() {
  const m = G.master; const opts = [];
  if (m.hp < m.hpMax * 0.6) opts.push('「顔色、最悪だよ。……別に心配してるわけじゃない。倒れられたら、運ぶのが面倒なだけ」');
  if (m.seals <= 1) opts.push('「令呪、もう残り少ないんだろ。平気な顔してるけど、さっきから手の甲ばっかり気にしてる。……分かりやすいね、君」');
  const low = Object.entries(m.stats).reduce((a, b) => b[1] < a[1] ? b : a);
  opts.push(`「君、自分の${STAT_LABEL[low[0]]}のことを気にしてるでしょ。……気にするだけ無駄だよ。君の取り柄は、そこじゃない」`);
  opts.push('「今、『こいつ何考えてるんだろう』って思ったでしょ。……教えないよ。僕にも分からないし」');
  opts.push('「眠れてないね。夢の中まで戦争してる。……うるさいんだよ、こっちまで聞こえてくる」');
  return fmt(pick(opts));
}

