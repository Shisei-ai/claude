const isOberon = () => !!G.servant && G.servant.id === 'oberon';
// 仮面が外れたか（夢で本当の姿を見た／絆がとても深い）
const oberonUnmasked = () => isOberon() && (G.flags.oberonTrue || G.servant.bond >= 80);

// ---- 仮面の奥の声（ヴォーティガーン）：直球の皮肉。けれど、これも本心とは限らない ----
const OBERON_TRUE = [
  '「……ああ、最悪だ。こんな所で、君と呑気にお茶なんか飲んでる。反吐が出るほど、平和だね」',
  '「勘違いするなよ。僕は君の味方なんかじゃない。……ただ、君が最後にどこへ落ちるのか、一番近くで見ていたいだけだ」',
  '「人間なんて、大嫌いだ。……君を除いて、なんて言うと思った？ ――言わないよ。言うもんか」',
  '「虫唾が走るね、その真っ直ぐな目。……見透かされてるのは、どっちなんだか」',
  '「全部嘘さ。王子様も、優しい言葉も。……だから、君が今笑ってる理由も、嘘ってことにしておいてよ」',
  '「気持ち悪い。君といると、僕まで明日のことなんか考えてしまう。……本当に、最悪だ」',
];
function oberonAside() {
  return `<span class="vort">――ふと、声が低くなった。王子様の仮面の、その奥から。<br>${fmt(pick(OBERON_TRUE))}</span>`;
}

// ---- 見透かす：マスターの今の様子を言い当てる ----
function oberonSeeThrough() {
  const m = G.master; const opts = [];
  if (m.hp < m.hpMax * 0.6) opts.push('「君、今日は随分無理してるね。顔色でバレバレだよ。……ほら、座って。命令じゃないけど」');
  if (m.seals <= 1) opts.push('「令呪、もう残り少ないんだろう？ 平気な顔してるけど、指先がずっと手の甲を探ってる。……隠すの、下手だなあ」');
  const low = Object.entries(m.stats).reduce((a, b) => b[1] < a[1] ? b : a);
  opts.push(`「君さ、自分の${STAT_LABEL[low[0]]}のこと、ちょっと気にしてるでしょ。……分かるよ。僕にはそういうの、全部見えてる」`);
  opts.push('「今、『この人は何を考えてるんだろう』って思ったでしょ。……教えてあげない。でも、君が何を考えてるかは、僕には分かるよ」');
  opts.push('「眠れてないね、君。……夢の中まで、聖杯戦争をしてる。少しは僕に任せなよ。夢は僕の領分なんだから」');
  return fmt(pick(opts));
}

// ---- 会話にオベロンらしさを足す ----
{
  const baseTier = tierLine;
  tierLine = function (sv) {
    sv = sv || servantOf(G);
    if (sv.id === 'oberon' && isOberon()) {
      if (Math.random() < 0.25) return oberonSeeThrough();
      const line = baseTier(sv);
      return oberonUnmasked() && Math.random() < 0.3 ? line + oberonAside() : line;
    }
    return baseTier(sv);
  };
  // 夢で本当の姿を見られると、以後、仮面の奥の声が漏れるようになる
  const baseSay = say;
  say = function (key) {
    const r = baseSay(key);
    if (key === 'dreamSeen' && isOberon()) { G.flags.oberonTrue = true; return r + `<span class="vort">（その声は、いつもの王子様のものではなかった。もっと低く、乾いた――けれど、どこか安堵したような声だった）</span>`; }
    return r;
  };
}

