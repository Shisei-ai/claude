// ---- オベロンの場合、地の文の「照れ」「嬉し泣き」などを、彼らしい反応に置き換える ----
//   好意を滲ませない人物なので、共通の文章で「照れたように笑った」となる所を「鼻で笑った」などに
const OBERON_NARR = [
  ['泣きそうな顔で笑っていた', '何も言わずに、ただそこにいた'], ['誰よりも嬉しそうに笑っていた', '誰よりもつまらなそうな顔で、それでも最後まで席を立たなかった'],
  ['心から嬉しそうに笑った', '鼻で笑った'], ['照れたように笑った', '鼻で笑った'], ['嬉しそうに笑った', '小さく鼻を鳴らした'],
  ['泣きながら笑っていた', '何も言わずに見下ろしていた'], ['泣きながら、何度も頷いた', '何も言わずに、窓の外を見ていた'],
  ['子どものように声を上げて泣いた', '長いこと、黙り込んでいた'], ['声を上げて泣いた', '長いこと、黙り込んでいた'],
  ['泣きそうな顔で笑った', '肩をすくめた'], ['泣きそうな顔で', '真顔で'], ['泣きながら', '黙ったまま'], ['泣いた', '黙り込んだ'],
  ['照れくさそうに', '気だるげに'], ['照れたように', '面倒くさそうに'], ['誇らしげに胸を張った', '肩をすくめた'], ['誇らしげに', '面倒くさそうに'],
  ['嬉しそうだった', 'つまらなそうな顔をしていた'], ['嬉しそうに', 'つまらなそうに'], ['耳まで真っ赤になった', '真顔になった'],
  ['顔を赤くした', '眉をひそめた'], ['真っ赤になって', '真顔のまま'], ['目元を押さえていた', '目を逸らしていた'],
  ['優しく微笑んだ', '肩をすくめた'], ['穏やかな顔で頷いた', '気だるげに頷いた'], ['柔らかく笑った', '鼻で笑った'], ['微笑んだ', '肩をすくめた'],
  ['その肩が、かすかに震えていた', 'その背中は、何も語らなかった'],
  ['オベロンが笑っていた', 'オベロンが、呆れたように鼻で笑っていた'],
];
function oberonNarr(html) {
  if (typeof html !== 'string' || !html.includes('オベロン')) return html;
  // 台詞（「」の中）はそのまま。地の文のうち、オベロンが主語の文だけを置き換える
  return html.split(/(「[^」]*」)/).map(seg => seg.startsWith('「') ? seg
    : seg.split(/(?<=。)/).map(sent => {
      if (!/オベロン[はがも、]/.test(sent)) return sent;
      for (const [a, b] of OBERON_NARR) if (sent.includes(a)) sent = sent.replace(a, b);
      return sent;
    }).join('')).join('');
}
{
  const baseScene = scene;
  scene = function (s) {
    if (isOberon() && s && Array.isArray(s.body)) s = { ...s, body: s.body.map(oberonNarr) };
    return baseScene(s);
  };
}

