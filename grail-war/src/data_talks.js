function encTalkFor(r) {
  if (!r || r.servantId === 'ori' || r.encTalked || !G.servant) return null;
  if (isFuji()) return ENC_TALK.fuji[r.servantId] || null;
  if (isKishi() && (r.matrix || 0) >= 1) return ENC_TALK.kishi[r.servantId] || null;   // 岸波は、マトリクスで真名を解析した後に
  return null;
}
function encounterTalkScene(r, then) {
  r.encTalked = true; r.recognized = true;
  const sv = servantOf(r);
  const mx = isKishi() ? kishiMatrix(r) : '';   // 岸波：ここでマトリクスの解析が完了する
  const who = { me: M(), mine: SV(), enemy: sv.short };
  const lines = ENC_TALK[isFuji() ? 'fuji' : 'kishi'][r.servantId].map(([sp, t]) => {
    if (typeof t === 'function') t = t();
    if (sp === 'mine' && typeof t === 'object') { t = t[sid()] !== undefined ? t[sid()] : t._; if (!t) return ''; }
    if (sp === 'narr') return `<p>${t}</p>`;
    const cls = sp === 'me' ? 'shirou' : sp === 'mine' ? 'saber' : 'enemy';
    return `<p class="talk ${cls}"><b>${who[sp]}</b>「${t}」</p>`;
  }).filter(Boolean);
  if (mx) lines.unshift(`<p>${mx}</p>`);
  addLog(`${isFuji() ? 'かつての仲間' : '月で縁を結んだ英霊'}「${sv.name}」と対面した。`);
  scene({ title: '対面', sub: `${rivalLabel(r)}・${r.cls}`, reveal: true, body: lines,
    choices: [{ label: '戦いを始める', cls: 'primary', icon: 'battle', fn: then }] });
}
